// Capturas de todas las pantallas en modo normal (azul): node e2e/shots.cjs
const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
  const p = await ctx.newPage()
  const shot = async (name, full = false) => { await p.waitForTimeout(500); await p.screenshot({ path: `/tmp/s-${name}.png`, fullPage: full }) }
  await p.goto('http://localhost:4173/?t=2026-11-03T06:12')
  await p.waitForTimeout(1500)
  await shot('popup-entreno')
  await p.getByRole('button', { name: 'Abrir el entreno de hoy' }).click()
  await shot('entreno', true)
  await p.locator('.dock').getByRole('button', { name: 'Curro' }).click()
  for (let i = 0; i < 7; i++) await p.getByRole('button', { name: 'Sumar llamadas de captación' }).click()
  await p.getByLabel('Nueva tarea').fill('Visita piso Calle Prado 12')
  await p.getByLabel('Hora (opcional)').fill('11:30')
  await p.getByRole('button', { name: 'Añadir' }).click()
  await shot('curro', true)
  await p.locator('.dock').getByRole('button', { name: 'Diario' }).click()
  await shot('diario', true)
  await p.locator('.dock').getByRole('button', { name: 'Misiones' }).click()
  await shot('misiones')
  await p.locator('.dock').getByRole('button', { name: 'Estado' }).click()
  await p.getByRole('button', { name: 'Ajustes' }).click()
  await shot('ajustes', true)
  await p.locator('main .back').click()
  await shot('estado')
  await p.getByRole('button', { name: '¿Qué hago ahora?' }).click()
  await shot('whatnow')
  await b.close()
})()
